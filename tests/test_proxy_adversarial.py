class TestStreamingAdversarial:
    """Adversarial streaming tests — format strictness and edge cases."""

    def test_stream_chunks_have_required_fields(self, client: httpx.Client, any_model_live: str | None):
        """Every SSE chunk must have id, object, choices fields."""
        if any_model_live is None:
            pytest.skip("No live backend")
        with client.stream(
            "POST",
            "/v1/chat/completions",
            json={
                "model": any_model_live,
                "messages": [{"role": "user", "content": "Count 1 2 3"}],
                "max_tokens": 16,
                "stream": True,
            },
            timeout=30.0,
        ) as r:
            assert r.status_code == 200
            for line in r.iter_lines():
                if not line or line.startswith(":"):
                    continue
                assert line.startswith("data: "), f"Bad SSE line: {line[:80]}"
                payload = line[len("data: "):]
                if payload.strip() == "[DONE]":
                    break
                chunk = json.loads(payload)
                assert "id" in chunk, f"Chunk missing 'id': {chunk}"
                assert "object" in chunk, f"Chunk missing 'object': {chunk}"
                assert "choices" in chunk, f"Chunk missing 'choices': {chunk}"

    def test_stream_content_type_is_sse(self, client: httpx.Client, any_model_live: str | None):
        """Streaming response Content-Type must be text/event-stream."""
        if any_model_live is None:
            pytest.skip("No live backend")
        with client.stream(
            "POST",
            "/v1/chat/completions",
            json={
                "model": any_model_live,
                "messages": [{"role": "user", "content": "Hi"}],
                "max_tokens": 4,
                "stream": True,
            },
            timeout=30.0,
        ) as r:
            if r.status_code == 200:
                ct = r.headers.get("content-type", "")
                assert "text/event-stream" in ct, f"Expected SSE content-type, got: {ct}"

    def test_non_stream_content_type_is_json(self, client: httpx.Client, any_model_live: str | None):
        """Non-streaming response Content-Type must be application/json."""
        if any_model_live is None:
            pytest.skip("No live backend")
        r = _chat(client, any_model_live, "Hi")
        if r.status_code == 200:
            ct = r.headers.get("content-type", "")
            assert "application/json" in ct, f"Expected JSON content-type, got: {ct}"

    def test_stream_false_does_not_stream(self, client: httpx.Client, any_model_live: str | None):
        """Explicit stream=false must return complete JSON, not SSE."""
        if any_model_live is None:
            pytest.skip("No live backend")
        r = _chat(client, any_model_live, "Hi", stream=False)
        if r.status_code == 200:
            data = r.json()
            assert "choices" in data
            assert "message" in data["choices"][0], "Non-stream must have message, not delta"


