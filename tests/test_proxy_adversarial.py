class TestConcurrencyGuard:
    """Verify concurrency guard queues overflow instead of rejecting."""

    def test_concurrent_requests_complete(self, client: httpx.Client, any_model_live: str | None):
        """Multiple concurrent requests should all eventually complete (queued, not rejected)."""
        if any_model_live is None:
            pytest.skip("No live backend")
        n = 3  # modest concurrency — enough to exercise queue without overloading

        def _do_one(i: int) -> tuple[int, int]:
            r = _chat(client, any_model_live, f"Reply: {i}")
            return i, r.status_code

        with ThreadPoolExecutor(max_workers=n) as pool:
            futures = [pool.submit(_do_one, i) for i in range(n)]
            results = [f.result(timeout=60) for f in as_completed(futures)]

        statuses = [s for _, s in results]
        # All should succeed or at least not be 429 (queued, not rejected)
        for idx, status in results:
            assert status != 429, f"Request {idx} got 429 — guard rejected instead of queuing"

    def test_concurrency_status_in_health(self, client: httpx.Client):
        """Health endpoint should expose concurrency slot info if guard is loaded."""
        data = client.get("/v1/scillm/health").json()
        # concurrency field is optional — if present, validate structure
        if "concurrency" in data and data["concurrency"]:
            conc = data["concurrency"]
            assert isinstance(conc, dict), f"Expected dict, got {type(conc)}"


