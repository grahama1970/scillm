def _chat(client: httpx.Client, model: str, content: str | list, **kw) -> httpx.Response:
    if isinstance(content, str):
        messages = [{"role": "user", "content": content}]
    else:
        messages = [{"role": "user", "content": content}]
    payload = {"model": model, "messages": messages, "max_tokens": 16, "temperature": 0, **kw}
    return client.post("/v1/chat/completions", json=payload, timeout=45.0)


def _chat_raw(base_url: str, headers: dict, model: str, content: str, **kw) -> httpx.Response:
    """POST without pre-configured client — for auth edge-case tests."""
    payload = {
        "model": model,
        "messages": [{"role": "user", "content": content}],
        "max_tokens": 4,
        **kw,
    }
    return httpx.post(
        f"{base_url}/v1/chat/completions",
        json=payload,
        headers=headers,
        timeout=15.0,
    )


