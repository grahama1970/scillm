class TestJsonGuard:
    """Verify JSON guard validates/repairs responses when json_object requested."""

    def test_json_mode_returns_valid_json(self, client: httpx.Client, any_model_live: str | None):
        """Requesting json_object mode must produce parseable JSON content."""
        if any_model_live is None:
            pytest.skip("No live backend")
        r = _chat(
            client,
            any_model_live,
            'Return a JSON object with key "status" and value "ok".',
            response_format={"type": "json_object"},
        )
        if r.status_code == 200:
            data = r.json()
            content = data["choices"][0]["message"]["content"]
            parsed = json.loads(content)  # must not raise
            assert isinstance(parsed, dict), f"Expected dict, got {type(parsed)}"

    def test_json_mode_without_json_instruction(self, client: httpx.Client, any_model_live: str | None):
        """JSON mode with a non-JSON prompt should still return valid JSON or error cleanly."""
        if any_model_live is None:
            pytest.skip("No live backend")
        r = _chat(
            client,
            any_model_live,
            "Tell me about the weather today.",
            response_format={"type": "json_object"},
        )
        if r.status_code == 200:
            data = r.json()
            content = data["choices"][0]["message"]["content"]
            if content is not None:
                # JSON guard should ensure this is valid JSON or the proxy retries/errors
                try:
                    json.loads(content)
                except json.JSONDecodeError:
                    pytest.fail(f"JSON guard let through invalid JSON: {content[:200]}")
        elif r.status_code == 502:
            # 502 = json_validation_error is acceptable (guard caught and rejected)
            data = r.json()
            assert "json" in data.get("error", {}).get("type", "").lower() or \
                   "json" in data.get("error", {}).get("message", "").lower(), \
                   f"502 should mention JSON: {data}"

    def test_non_json_mode_passes_through(self, client: httpx.Client, any_model_live: str | None):
        """Without json_object mode, prose responses pass through unchanged."""
        if any_model_live is None:
            pytest.skip("No live backend")
        r = _chat(client, any_model_live, "Say hello in one word.")
        if r.status_code == 200:
            content = r.json()["choices"][0]["message"]["content"]
            assert len(content) > 0, "Response should have content"


